'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict'),http=require('node:http');
const create=require('../analysis-service');
test('fila FIFO compartilhada, prioridade interrompe com segurança, queda e falha liberam o próximo',async t=>{
  const members=new Set(['a','b'].map(id=>({id,uploadToken:id,presence:{i:'baixo'}})));
  const room={code:'queue',members,playlist:['A','B','C'].map(key=>({meta:{key}}))},events=[];
  const service=create({rooms:new Map([['queue',room]]),broadcast:(_,e)=>events.push(e),announce(){}});
  const server=http.createServer((req,res)=>service.handle(req,res,new URL(req.url,'http://localhost')));
  await new Promise(r=>server.listen(0,'127.0.0.1',r));
  t.after(async()=>{await service.release(room);await new Promise(r=>server.close(r));});
  const req=(route,key,token='a',options={})=>fetch('http://127.0.0.1:'+server.address().port+'/api/analysis'+route+'?room=queue'+(key?'&key='+key:''),{...options,headers:{'X-Jam-Token':token,...options.headers}});
  const queue=async()=> (await req('/queue')).json();
  assert.deepEqual((await queue()).jobs.map(j=>j.key),['A','B','C']);
  assert.equal((await req('/claim','B','b',{method:'POST'})).status,409);
  const simultaneous=await Promise.all(['a','b'].map(token=>req('/claim','A',token,{method:'POST'})));
  assert.deepEqual(simultaneous.map(r=>r.status).sort(),[200,409]);
  const claimed=await simultaneous.find(r=>r.status===200).json();
  assert.equal((await req('/claim','C','b',{method:'POST'})).status,409);
  assert.equal((await req('/prioritize','C','b',{method:'POST'})).status,200);
  assert.deepEqual((await queue()).jobs.map(j=>[j.key,j.status]),[['C','queued'],['A','queued'],['B','queued']]);
  assert.equal((await req('/progress','A',claimed.owner,{method:'POST',headers:{'X-Analysis-Lease':claimed.lease},body:'{}'})).status,403);
  const c=await(await req('/claim','C','b',{method:'POST'})).json();assert.ok(c.lease);
  service.peerLeft(room,'b');assert.equal((await queue()).jobs[0].status,'queued');
  const c2=await(await req('/claim','C','a',{method:'POST'})).json();assert.ok(c2.lease);
  const diagnostic={message:'Falha ao iniciar o motor.',details:'WebAssembly: Failed to initialize backend',stage:'Iniciando a separação'};
  assert.equal((await req('/fail','C','b',{method:'POST',headers:{'X-Analysis-Lease':c2.lease},body:JSON.stringify(diagnostic)})).status,403);
  assert.equal((await req('/fail','C','a',{method:'POST',headers:{'X-Analysis-Lease':c2.lease},body:JSON.stringify(diagnostic)})).status,200);
  const failed=(await queue()).jobs[0];assert.equal(failed.message,diagnostic.message);assert.equal(failed.error.details,diagnostic.details);assert.equal(failed.error.stage,diagnostic.stage);
  await req('/prioritize','C','a',{method:'POST'});
  const c3=await(await req('/claim','C','a',{method:'POST'})).json();assert.ok(c3.lease);
  assert.equal((await queue()).jobs[0].error,undefined);
  assert.equal((await req('/cancel','C','a',{method:'POST',headers:{'X-Analysis-Lease':c3.lease}})).status,200);
  assert.equal((await queue()).jobs[0].status,'error');
  assert.ok((await(await req('/claim','A','a',{method:'POST'})).json()).lease);
  room.playlist=room.playlist.filter(s=>s.meta.key!=='A');await service.remove(room,'A');
  assert.ok((await(await req('/claim','B','b',{method:'POST'})).json()).lease);
  assert.ok(events.some(e=>e.type==='analysisQueue'));assert.equal(service.stats().diskBytes,0);
});
