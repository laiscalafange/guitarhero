'use strict';
const {test}=require('node:test');const assert=require('node:assert/strict');const http=require('node:http');
const create=require('../analysis-service');
test('análise compartilhada: um dono, isolamento, arquivos por streaming e liberação',async t=>{
  const c={id:'a',uploadToken:'token',presence:{i:'teclado'}},other={id:'b',uploadToken:'other',presence:{i:'baixo'}};
  const room={code:'test-ai',members:new Set([c,other]),playlist:[{meta:{key:'f:abc'}}],song:{meta:{key:'f:abc'}}};
  const service=create({rooms:new Map([[room.code,room]]),broadcast:()=>{},announce:()=>{}});
  const server=http.createServer((req,res)=>service.handle(req,res,new URL(req.url,'http://localhost')));
  await new Promise(r=>server.listen(0,'127.0.0.1',r));t.after(async()=>{await service.release(room);await new Promise(r=>server.close(r));});
  const base='http://127.0.0.1:'+server.address().port;
  const req=(route,options={})=>fetch(base+'/api/analysis'+route+(route.includes('?')?'&':'?')+'room=test-ai&key=f:abc',{...options,headers:{'X-Jam-Token':'token',...(options.headers||{})}});
  const claim=await(await req('/claim',{method:'POST'})).json();assert.ok(claim.lease);
  assert.equal((await req('/claim',{method:'POST',headers:{'X-Jam-Token':'other'}})).status,409);
  assert.equal((await req('/complete',{method:'POST',body:'{}'})).status,403);
  const wav=Buffer.alloc(44+44100);wav.write('RIFF');wav.writeUInt32LE(wav.length-8,4);wav.write('WAVE',8);wav.write('fmt ',12);wav.writeUInt32LE(16,16);wav.writeUInt16LE(1,20);wav.writeUInt16LE(1,22);wav.writeUInt32LE(22050,24);wav.writeUInt32LE(44100,28);wav.writeUInt16LE(2,32);wav.writeUInt16LE(16,34);wav.write('data',36);wav.writeUInt32LE(wav.length-44,40);
  const headers={'X-Analysis-Lease':claim.lease};
  assert.equal((await req('/stem?instrument=vocal',{method:'PUT',headers,body:wav})).status,200);
  assert.equal(service.stats().diskBytes,wav.length);
  const manifest={version:1,duration:1,instruments:['vocal'],events:{vocal:[{t:.1,pitch:60,dur:.5,s:.8}]}};
  const completed=await req('/complete',{method:'POST',headers,body:JSON.stringify(manifest)});assert.equal(completed.status,200,await completed.clone().text());
  assert.equal(c.presence.i,'vocal');assert.equal(other.presence.i,'vocal');
  assert.equal((await(await req('/manifest')).json()).events.vocal[0].t,.1);
  assert.equal((await(await req('/stem?instrument=vocal')).arrayBuffer()).byteLength,wav.length);
  assert.equal((await req('/manifest',{headers:{'X-Jam-Token':'bad'}})).status,403);
  assert.ok(service.stats().chartBytes>0);
  await service.release(room);assert.equal(service.stats().diskBytes,0);assert.equal(service.stats().chartBytes,0);
  const claim2=await(await req('/claim',{method:'POST'})).json();
  const small=Buffer.from(wav.subarray(0,44+22050));small.writeUInt32LE(small.length-8,4);small.writeUInt32LE(22050,28);small.writeUInt16LE(1,32);small.writeUInt16LE(8,34);small.writeUInt32LE(22050,40);
  const headers2={'X-Analysis-Lease':claim2.lease};
  assert.equal((await req('/stem?instrument=vocal',{method:'PUT',headers:headers2,body:small})).status,200);
  assert.equal((await req('/complete',{method:'POST',headers:headers2,body:JSON.stringify({...manifest,audioFormat:'pcm8-mono-22050'})})).status,200);
  assert.equal((await(await req('/manifest')).json()).audioFormat,'pcm8-mono-22050');
  await service.release(room);
  await req('/claim',{method:'POST'});
  service.peerLeft(room,'a');
  assert.equal((await(await req('')).json()).status,'queued');
  assert.equal((await req('/claim',{method:'POST',headers:{'X-Jam-Token':'other'}})).status,200);
});
